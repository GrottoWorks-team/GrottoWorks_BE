namespace TaskExecution.Domain.Support;

public enum SupportType { Staffing, Material, Mixed }
public enum SupportRequestStatus { Planning, Published, PartiallyFulfilled, Fulfilled, Closed, Cancelled }
public sealed record SupportSkillInput(Guid SkillId,string? RequiredSkillLevel);
public sealed record SupportPositionInput(Guid? Id,string Name,int RequiredVolunteerCount,string? Note,IReadOnlyList<SupportSkillInput> Skills);
public sealed record SupportMaterialInput(Guid? Id,Guid MaterialId,decimal RequiredQuantity,string? Note);

public sealed partial class SupportRequest
{
    private readonly List<SupportPosition> positions=[];
    private readonly List<SupportMaterial> materials=[];
    private SupportRequest() { }
    public Guid Id {get;private set;}
    public Guid SeasonId {get;private set;}
    public Guid WorkAreaId {get;private set;}
    public Guid RequestedBy {get;private set;}
    public SupportType SupportType {get;private set;}
    public string? Description {get;private set;}
    public DateOnly? Deadline {get;private set;}
    public SupportRequestStatus Status {get;private set;}
    public DateTimeOffset CreatedAt {get;private set;}
    public DateTimeOffset? UpdatedAt {get;private set;}
    public int Version {get;private set;}=1;
    public IReadOnlyCollection<SupportPosition> Positions=>positions;
    public IReadOnlyCollection<SupportMaterial> Materials=>materials;

    public static SupportRequest Create(Guid seasonId,Guid areaId,Guid actor,SupportType type,string? description,DateOnly? deadline,
        IReadOnlyList<SupportPositionInput> positions,IReadOnlyList<SupportMaterialInput> materials,DateTimeOffset now)
    {
        if (seasonId==Guid.Empty || areaId==Guid.Empty || actor==Guid.Empty)
            throw DomainRuleException.Validation("SUPPORT_IDENTITY_INVALID","Season, work area and actor are required.");
        if (!Enum.IsDefined(type)) throw DomainRuleException.Validation("SUPPORT_TYPE_INVALID","Invalid support type.");
        if (positions.Any(p=>p.Id.HasValue) || materials.Any(m=>m.Id.HasValue))
            throw DomainRuleException.Validation("SUPPORT_LINE_ID_INVALID","New line IDs are generated by the server.");
        var request=new SupportRequest
        {
            Id=Guid.NewGuid(),SeasonId=seasonId,WorkAreaId=areaId,RequestedBy=actor,SupportType=type,
            Description=NormalizeNote(description),Deadline=deadline,Status=SupportRequestStatus.Planning,CreatedAt=now.ToUniversalTime()
        };
        request.positions.AddRange(BuildPositions(request.Id,positions));
        request.materials.AddRange(BuildMaterials(request.Id,materials));
        return request;
    }

    private static List<SupportPosition> BuildPositions(Guid requestId,IReadOnlyList<SupportPositionInput> inputs)
    {
        var rows=new List<SupportPosition>();var names=new HashSet<string>(StringComparer.OrdinalIgnoreCase);
        foreach(var input in inputs)
        {
            var name=input.Name?.Trim();
            if (string.IsNullOrWhiteSpace(name) || name.Length>150 || input.RequiredVolunteerCount<=0)
                throw DomainRuleException.Validation("SUPPORT_POSITION_INVALID","Each position requires a name (1–150) and a positive headcount.");
            if (!names.Add(name)) throw DomainRuleException.Validation("SUPPORT_POSITION_DUPLICATE","Position names must not repeat.");
            rows.Add(SupportPosition.Create(input.Id??Guid.NewGuid(),requestId,name,input.RequiredVolunteerCount,NormalizeNote(input.Note),input.Skills));
        }
        return rows;
    }

    private static List<SupportMaterial> BuildMaterials(Guid requestId,IReadOnlyList<SupportMaterialInput> inputs)
    {
        var rows=new List<SupportMaterial>();var ids=new HashSet<Guid>();
        foreach(var input in inputs)
        {
            if (input.MaterialId==Guid.Empty || input.RequiredQuantity<=0 || input.RequiredQuantity>9999999999.99m ||
                decimal.Round(input.RequiredQuantity,2)!=input.RequiredQuantity)
                throw DomainRuleException.Validation("SUPPORT_MATERIAL_INVALID","Material ID and positive quantity with at most two decimals are required.");
            if (!ids.Add(input.MaterialId)) throw DomainRuleException.Validation("SUPPORT_MATERIAL_DUPLICATE","A material can only appear once.");
            rows.Add(SupportMaterial.Create(input.Id??Guid.NewGuid(),requestId,input.MaterialId,input.RequiredQuantity,NormalizeNote(input.Note)));
        }
        return rows;
    }

    private static string? NormalizeNote(string? value)
    {
        var normalized=string.IsNullOrWhiteSpace(value) ? null : value.Trim();
        if (normalized?.Length>2000) throw DomainRuleException.Validation("SUPPORT_NOTE_INVALID","Text must not exceed 2000 characters.");
        return normalized;
    }
}

public sealed class SupportPosition
{
    private readonly List<SupportPositionSkill> skills=[];
    private SupportPosition() { }
    public Guid Id {get;private set;}
    public Guid RequestId {get;private set;}
    public string Name {get;private set;}="";
    public int RequiredVolunteerCount {get;private set;}
    public string? Note {get;private set;}
    public IReadOnlyCollection<SupportPositionSkill> Skills=>skills;
    internal static SupportPosition Create(Guid id,Guid request,string name,int count,string? note,IReadOnlyList<SupportSkillInput> inputs)
    {
        var row=new SupportPosition {Id=id,RequestId=request,Name=name,RequiredVolunteerCount=count,Note=note};
        var ids=new HashSet<Guid>();
        foreach(var input in inputs)
        {
            var level=string.IsNullOrWhiteSpace(input.RequiredSkillLevel) ? null : input.RequiredSkillLevel.Trim();
            if (input.SkillId==Guid.Empty || level?.Length>30)
                throw DomainRuleException.Validation("SUPPORT_SKILL_INVALID","Skill ID is required; skill level must not exceed 30 characters.");
            if (!ids.Add(input.SkillId)) throw DomainRuleException.Validation("SUPPORT_SKILL_DUPLICATE","A skill can only appear once per position.");
            row.skills.Add(SupportPositionSkill.Create(id,input.SkillId,level));
        }
        return row;
    }
}

public sealed class SupportPositionSkill
{
    private SupportPositionSkill() { }
    public Guid PositionId {get;private set;}
    public Guid SkillId {get;private set;}
    public string? RequiredSkillLevel {get;private set;}
    internal static SupportPositionSkill Create(Guid position,Guid skill,string? level)=>new() {PositionId=position,SkillId=skill,RequiredSkillLevel=level};
}

public sealed class SupportMaterial
{
    private SupportMaterial() { }
    public Guid Id {get;private set;}
    public Guid RequestId {get;private set;}
    public Guid MaterialId {get;private set;}
    public decimal RequiredQuantity {get;private set;}
    public string? Note {get;private set;}
    internal static SupportMaterial Create(Guid id,Guid request,Guid material,decimal quantity,string? note)=>new()
    {Id=id,RequestId=request,MaterialId=material,RequiredQuantity=quantity,Note=note};
}
